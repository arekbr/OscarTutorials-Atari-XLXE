#define STRIP ((volatile byte *)0x6000)
#define STRIP_PITCH 128

static const byte layer[7] = { 0, 1, 1, 2, 2, 2, 2 };

static const byte mountains[][8] = {
    { 0, 0, 0, 0, 0, 0, 0, 0 },
    { 255, 255, 255, 255, 255, 255, 255, 255 },
    { 1, 3, 7, 15, 31, 63, 127, 255 },
    { 128, 192, 224, 240, 248, 252, 254, 255 },
    { 0, 0, 1, 3, 7, 15, 63, 255 },
    { 0, 0, 128, 192, 224, 240, 252, 255 },
    { 255, 255, 254, 252, 248, 240, 192, 0 },
    { 255, 255, 127, 63, 31, 15, 3, 0 },
};

static byte mountain_glyph(byte source)
{
    switch (source)
    {
        case 0xa0: return 1;
        case 0x4e: return 2;
        case 0xdf: return 3;
        case 0x64: return 4;
        case 0x6f: return 5;
        case 0xe4: return 6;
        case 0xef: return 7;
        case 0x20: return 0;
        default: return 1;
    }
}

int main(void)
{
    clear_dma(TEXT, 960);
    copy_dma(FONT, (const byte *)mountains, sizeof(mountains));
    for (byte y = 0; y < 7; y++)
    {
        volatile byte *dst = STRIP + (word)y * STRIP_PITCH;
        for (byte x = 0; x < 88; x++)
            dst[x] = mountain_glyph(ParaLines[40 * y + x % 40]);
    }

    display_off();
    CHBAS = 0x88;
    list_begin();
    for (byte y = 0; y < 16; y++)
        list_line(y == 15 ? 0x82 : 2, TEXT + 40 * y);
    for (byte y = 0; y < 7; y++)
        list_line(y == 0 || y == 2 ? 0x92 : 0x12, STRIP + (word)y * STRIP_PITCH);
    list_end();
    band_hue[0] = 0x92;
    band_hue[1] = 0xa6;
    band_hue[2] = 0xc4;
    bands_on(3);

    word frame = 0;
    for (;;)
    {
        wait_blank();
        frame++;
        word time[3] = { frame >> 1, frame, frame << 1 };
        for (byte i = 0; i < 3; i++)
            band_fine[i] = 12 - (time[i] & 3);
        for (byte y = 0; y < 7; y++)
            DL[52 + 3 * y] = (byte)((word)y * STRIP_PITCH) +
                             ((time[layer[y]] >> 2) % 40);
    }
}
