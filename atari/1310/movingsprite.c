#include "../common/shape.h"

static const byte SpriteImage[64] = {
	0b00000000, 0b11111000, 0b00000000,
	0b00000011, 0b11111110, 0b00000000,
	0b00001111, 0b11111111, 0b10000000,
	0b00011111, 0b11111111, 0b11000000,
	0b00111111, 0b11111111, 0b11100000,
	0b00111111, 0b11111111, 0b11100000,
	0b01111111, 0b11111111, 0b11110000,
	0b01111111, 0b11111111, 0b11110000,
	0b11111111, 0b11111111, 0b11111000,
	0b11111111, 0b11111111, 0b11111000,
	0b11111111, 0b11111111, 0b11111000,
	0b11111111, 0b11111111, 0b11111000,
	0b11111111, 0b11111111, 0b11111000,
	0b01111111, 0b11111111, 0b11110000,
	0b01111111, 0b11111111, 0b11110000,
	0b00111111, 0b11111111, 0b11100000,
	0b00111111, 0b11111111, 0b11100000,
	0b00011111, 0b11111111, 0b11000000,
	0b00001111, 0b11111111, 0b10000000,
	0b00000011, 0b11111110, 0b00000000,
	0b00000000, 0b11111000, 0b00000000
};

int main(void)
{
    byte shape[21];
    player_shape(SpriteImage, shape);
    sprite_stage();
    for (byte i = 0; i < 4; i++)
        PCOLOR(i) = player_colors[i];

    byte last[4] = { 0, 0, 0, 0 };
    byte offset = 0;
    for (;;)
    {
        wait_blank();
        for (byte i = 0; i < 4; i++)
        {
            byte y = 32 + (offset + 43 * i) % 170;

            player_erase(i, last[i], 21);
            player_draw(i, 56 + 37 * i, y, shape, 21);
            last[i] = y;
        }
        if (++offset == 170)
            offset = 0;
    }
}
