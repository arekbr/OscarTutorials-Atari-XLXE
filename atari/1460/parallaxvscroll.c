static void rebuild(byte y)
{
    volatile byte *dst = scroll_back;
    for (byte row = 0; row < 25; row++)
    {
        const byte *src = (const byte *)Lines + 40 * ((y + row) & 7);
        copy_dma(dst, src, 40);
        dst += 40;
    }
}

int main(void)
{
    copy_dma(FONT, (const byte *)CharSet, sizeof(CharSet));
    clear_dma(TEXT, 960);
    text_display(2, true);
    byte phase = 0;
    volatile byte *next = DL;
    for (;;)
    {
        if (!(phase & 7))
        {
            rebuild(phase >> 3);
            next = prepare_scroll(scroll_back, 2, 40, false, true);
            scroll_flip();
        }
        publish_scroll(next, 0, phase & 7);
        byte shift = 7 - ((phase >> 1) & 7);
        for (byte glyph = 1; glyph < 5; glyph++)
            for (byte y = 0; y < 8; y++)
                FONT[8 * glyph + y] = CharSet[8 * glyph + ((y + shift) & 7)];
        phase++;
    }
}
